import ExcelJS from 'exceljs';
import PDFDocument from 'pdfkit';

export interface ReportColumn {
  key: string;
  label: string;
  type?: 'text' | 'int' | 'pct' | 'date';
}

export interface ReportData {
  id: string;
  title: string;
  generatedAt: Date;
  generatedBy: string;
  period: string;
  scope: string;
  filters: Record<string, string>;
  source: string;
  validationStatus: string;
  limitations: string[];
  synthetic: boolean;
  columns: ReportColumn[];
  rows: Record<string, unknown>[];
  definitions?: { term: string; definition: string }[];
}

const fmt = (v: unknown, type?: ReportColumn['type']): string => {
  if (v === null || v === undefined || v === '') return '';
  if (type === 'int' && typeof v === 'number') return v.toLocaleString('en-NG');
  if (type === 'pct' && typeof v === 'number') return `${(v * 100).toFixed(1)}%`;
  if (type === 'date') return new Date(v as string).toISOString().replace('T', ' ').slice(0, 16) + ' UTC';
  return String(v);
};

function metaLines(r: ReportData): [string, string][] {
  return [
    ['Report', r.title],
    ['Generated', r.generatedAt.toISOString().replace('T', ' ').slice(0, 19) + ' UTC'],
    ['Generated by', r.generatedBy],
    ['Reporting period', r.period],
    ['Geographic scope', r.scope],
    ['Filters', Object.entries(r.filters).map(([k, v]) => `${k}=${v}`).join('; ') || 'None'],
    ['Source', r.source],
    ['Validation status', r.validationStatus],
    ['Limitations', r.limitations.join(' | ')],
    ...(r.synthetic ? ([['Data notice', 'SYNTHETIC DEMONSTRATION DATA — NOT OFFICIAL STATISTICS']] as [string, string][]) : []),
  ];
}

/** Neutralises spreadsheet formula injection. */
function csvCell(v: unknown): string {
  let s = v === null || v === undefined ? '' : String(v);
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function renderCsv(r: ReportData): Buffer {
  const lines: string[] = [];
  for (const [k, v] of metaLines(r)) lines.push(`# ${k}: ${v.replace(/[\r\n]+/g, ' ')}`);
  lines.push(r.columns.map((c) => csvCell(c.label)).join(','));
  for (const row of r.rows) lines.push(r.columns.map((c) => csvCell(row[c.key])).join(','));
  return Buffer.from('﻿' + lines.join('\r\n') + '\r\n', 'utf8');
}

export async function renderXlsx(r: ReportData): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Lagos Electoral Intelligence Platform';
  wb.created = r.generatedAt;
  const ws = wb.addWorksheet('Report', { views: [{ state: 'frozen', ySplit: metaLines(r).length + 2 }] });
  ws.addRow([r.title]).font = { bold: true, size: 14 };
  for (const [k, v] of metaLines(r).slice(1)) {
    const row = ws.addRow([k, v]);
    row.getCell(1).font = { bold: true };
    if (k === 'Data notice') row.getCell(2).font = { bold: true, color: { argb: 'FFB91C1C' } };
  }
  const header = ws.addRow(r.columns.map((c) => c.label));
  header.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  header.eachCell((cell) => (cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF14532D' } }));
  for (const row of r.rows) {
    ws.addRow(
      r.columns.map((c) => {
        const v = row[c.key];
        if (c.type === 'date' && v) return new Date(v as string);
        if (typeof v === 'string' && /^[=+\-@]/.test(v)) return `'${v}`;
        return v ?? null;
      }),
    );
  }
  r.columns.forEach((c, i) => {
    const col = ws.getColumn(i + 1);
    col.width = Math.min(48, Math.max(12, c.label.length + 2));
    if (c.type === 'int') col.numFmt = '#,##0';
    if (c.type === 'pct') col.numFmt = '0.0%';
    if (c.type === 'date') col.numFmt = 'yyyy-mm-dd hh:mm';
  });
  ws.getColumn(1).width = Math.max(ws.getColumn(1).width ?? 12, 20);
  if (r.definitions?.length) {
    const d = wb.addWorksheet('Definitions');
    d.addRow(['Term', 'Definition']).font = { bold: true };
    for (const x of r.definitions) d.addRow([x.term, x.definition]);
    d.getColumn(1).width = 32;
    d.getColumn(2).width = 110;
  }
  return Buffer.from(await wb.xlsx.writeBuffer());
}

export function renderPdf(r: ReportData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', layout: r.columns.length > 6 ? 'landscape' : 'portrait', margin: 40, bufferPages: true, info: { Title: r.title, Author: 'Lagos Electoral Intelligence Platform' } });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    const W = doc.page.width - 80;

    doc.fillColor('#14532d').fontSize(16).font('Helvetica-Bold').text(r.title);
    doc.moveDown(0.3);
    if (r.synthetic) {
      doc.fillColor('#b91c1c').fontSize(10).font('Helvetica-Bold').text('SYNTHETIC DEMONSTRATION DATA — NOT OFFICIAL STATISTICS');
      doc.moveDown(0.3);
    }
    doc.fillColor('#111').fontSize(8.5);
    for (const [k, v] of metaLines(r).slice(1)) {
      if (k === 'Data notice') continue;
      doc.font('Helvetica-Bold').text(`${k}: `, { continued: true }).font('Helvetica').text(v);
    }
    doc.moveDown(0.6);

    // Table
    const weights = r.columns.map((c) => (c.type === 'text' || !c.type ? 2.2 : 1));
    const total = weights.reduce((a, b) => a + b, 0);
    const widths = weights.map((w) => (w / total) * W);
    const rowH = 15;
    const drawHeader = () => {
      let x = 40;
      const y = doc.y;
      doc.rect(40, y, W, rowH + 4).fill('#14532d');
      doc.fillColor('#fff').font('Helvetica-Bold').fontSize(8);
      r.columns.forEach((c, i) => {
        doc.text(c.label, x + 3, y + 4, { width: widths[i]! - 6, height: rowH, ellipsis: true, align: c.type && c.type !== 'text' ? 'right' : 'left' });
        x += widths[i]!;
      });
      doc.y = y + rowH + 4;
      doc.fillColor('#111').font('Helvetica').fontSize(8);
    };
    drawHeader();
    r.rows.forEach((row, n) => {
      if (doc.y + rowH > doc.page.height - 50) {
        doc.addPage();
        drawHeader();
      }
      const y = doc.y;
      if (n % 2 === 1) doc.rect(40, y, W, rowH).fill('#f1f5f2').fillColor('#111');
      let x = 40;
      r.columns.forEach((c, i) => {
        doc.text(fmt(row[c.key], c.type), x + 3, y + 3.5, { width: widths[i]! - 6, height: rowH, ellipsis: true, lineBreak: false, align: c.type && c.type !== 'text' ? 'right' : 'left' });
        x += widths[i]!;
      });
      doc.y = y + rowH;
    });
    if (!r.rows.length) doc.moveDown().text('No rows match the selected scope and filters.');

    if (r.definitions?.length) {
      doc.addPage();
      doc.font('Helvetica-Bold').fontSize(11).text('Definitions');
      doc.moveDown(0.4).fontSize(8.5);
      for (const d of r.definitions) doc.font('Helvetica-Bold').text(d.term).font('Helvetica').text(d.definition).moveDown(0.3);
    }

    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      const bottom = doc.page.height - 30;
      doc.fontSize(7).fillColor('#555').font('Helvetica');
      doc.text(`${r.title} · ${r.scope} · generated ${r.generatedAt.toISOString().slice(0, 16).replace('T', ' ')} UTC · page ${i + 1} of ${range.count}`, 40, bottom, { width: W, align: 'center', lineBreak: false });
      if (r.synthetic) doc.fillColor('#b91c1c').text('SYNTHETIC DEMONSTRATION DATA', 40, bottom - 10, { width: W, align: 'center', lineBreak: false });
    }
    doc.end();
  });
}
